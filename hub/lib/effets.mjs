// --- outils -----------------------------------------------------------------

function rx(src) { try { return new RegExp(src, 'iu'); } catch { return null; } }
function compilerRegles(list) {
  return (Array.isArray(list) ? list : []).map((r) => ({ re: rx(String(r.motif || '')), effet: r.effet })).filter((r) => r.re && r.effet);
}
function existe(rel) { if (!rel) return false; const st = statSafe(path.join(ROOT, rel)); return !!(st && st.isFile()); }
function siExiste(rel) { return existe(rel) ? rel : null; }
function humaniser(s) {
  return String(s || '').replace(/[-_.]+/g, ' ').replace(/\s+/g, ' ').trim().replace(/^./, (c) => c.toUpperCase());
}
function uniq(arr) { return [...new Set(arr.filter(Boolean))]; }

export function lireVocabulaire() {
  const v = readJSONSafe(FICHIERS.vocabulaire, 1024 * 1024);
  if (!v || !Array.isArray(v.effets) || !v.effets.length) throw new Error(`vocabulaire absent ou vide : ${FICHIERS.vocabulaire}`);
  return v;
}
export function lireMapping() {
  const m = readJSONSafe(FICHIERS.mapping, 4 * 1024 * 1024);
  if (!m) throw new Error(`mapping absent ou invalide : ${FICHIERS.mapping}`);
  return m;
}

/** En-tête d'une carte : dimensions (data-width/height) et commentaire de description. */
function enteteCarte(rel) {
  let txt;
  try { txt = fs.readFileSync(path.join(ROOT, rel), 'utf8'); } catch { return null; }
  const mw = /data-width="(\d+)"/.exec(txt);
  const mh = /data-height="(\d+)"/.exec(txt);
  const mc = /<!--([\s\S]*?)-->/.exec(txt.slice(0, 6000));
  let lignes = [];
  if (mc) {
    lignes = mc[1].split('\n').map((l) => l.trim()).filter(Boolean)
      .filter((l) => !/GENERATED by|do not hand-edit|edit the template|^edit the/i.test(l));
  }
  // la première ligne est souvent l'en-tête « KALLAWAY · tier1 · section · ASCEND » :
  // le nom du style en capitales, puis des segments séparés par « · ». Son
  // dernier segment est le meilleur titre qu'on ait (« SPOTLIGHT JAUNE »).
  let entete = null;
  let titre = null;
  if (lignes.length && / · /.test(lignes[0]) && /^[A-ZÀ-Ý][A-ZÀ-Ý0-9 \-]+ · /.test(lignes[0]) && lignes[0].length < 120) {
    entete = lignes.shift();
    const seg = entete.split(' · ').pop().trim();
    const m = /^(.*?)\s*\(([^)]*)\)\s*$/.exec(seg); // « SPOTLIGHT (depth-of-field) »
    titre = casseDePhrase(m ? m[1] : seg);
    if (m && m[2]) titre += ` (${m[2]})`;
  }
  const commentaire = lignes.join(' ').replace(/\s+/g, ' ').trim();
  return { w: mw ? Number(mw[1]) : null, h: mh ? Number(mh[1]) : null, entete, titre, commentaire: commentaire.slice(0, 420) };
}

/** « L'UI REJOUÉE QUI S'EXÉCUTE » -> « L'UI rejouée qui s'exécute » (les sigles restent en capitales). */
function casseDePhrase(s) {
  const SIGLES = /^(UI|PIP|CTA|LED|HUD|IA|AI|TV|URL|API|CSS|SVG|UGC|VHS|RGB|RVB|ASCII|PNG|MP4|GIF|SFX|VU|DJI|X|AB|B2B|CTR|CPM|KPI|LUT|FX|OS|PDF|FAQ|CEO|SEO|GPT|LLM|HTML|JS|GSAP|PNL)$/;
  const mots = String(s || '').trim().split(/\s+/);
  return mots.map((m, i) => {
    const el = /^([LDJSNMCT]['’]|QU['’])(.+)$/i.exec(m); // L'UI, D'UN, S'EXÉCUTE
    const pref = el ? el[1] : '';
    let coeur = el ? el[2] : m;
    const nu = coeur.replace(/[^A-ZÀ-Ý0-9]/g, '');
    const garde = coeur === coeur.toUpperCase() && (/\d/.test(nu) || SIGLES.test(nu));
    if (!garde) coeur = coeur.toLowerCase();
    let out = (i === 0 ? pref.charAt(0).toUpperCase() + pref.slice(1).toLowerCase() : pref.toLowerCase()) + coeur;
    if (i === 0 && !pref && !garde) out = out.charAt(0).toUpperCase() + out.slice(1);
    return out;
  }).join(' ');
}

