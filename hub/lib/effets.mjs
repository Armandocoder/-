// La bibliothèque d'EFFETS : une grille à deux facettes, chaîne source × type
// d'effet, construite depuis la v1 (style-library/registry.json, les fiches
// Pocinho et les styles de motion-library) sans rien y écrire.
//
//   donnees/effets/vocabulaire.json  les types d'effets, vocabulaire fermé
//   donnees/effets/mapping.json      purpose/traitement/technique -> effet
//   donnees/effets/index.json        GÉNÉRÉ : les entrées, les chaînes, la matrice
//   donnees/effets/INDEX.md          GÉNÉRÉ : la même chose, lisible par design-beats
//
// Une entrée est une CARTE jouable : un HTML HyperFrames autonome, à monter en
// data-composition-src dans un montage. C'est la boîte à outils, pas l'inspiration :
// les références (Pocinho, Prompt Motion, les styles comme styles) vivent dans la
// VITRINE (hub/lib/vitrine.mjs), à regarder et à imiter, jamais à monter.
// Les 1 100 variantes générées de Higgsfield se replient en une entrée par
// chaîne × effet, avec la liste de leurs traitements pour choisir.

