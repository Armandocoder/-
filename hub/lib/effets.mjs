/** Construit et écrit index.json + INDEX.md. Retourne { index, diagnostic }. */
export function ecrireEffets() {
  const r = construireEffets();
  ecrireJSON(FICHIERS.index, r.index);
  fs.writeFileSync(FICHIERS.md, rendreIndexMd(r.index));
  return r;
}

/**
 * L'index tel que le hub le sert : lu sur le disque (construit s'il manque),
 * avec les épingles du moment appliquées par-dessus, sans reconstruction.
 */
export function lireEffets() {
  let index = readJSONSafe(FICHIERS.index, 64 * 1024 * 1024);
  if (!index) index = ecrireEffets().index;
  const ep = lireEpingles();
  appliquerEpingles(index.entrees, ep);
  for (const c of index.chaines) c.epingle = !!(ep.get(`style-${c.id}`) && ep.get(`style-${c.id}`).epingle);
  index.resume.epinglees = index.entrees.filter((x) => x.epingle).length;
  appliquerMaCharte(index);
  return index;
}

/** Après une épingle : INDEX.md doit suivre sans reconstruire tout l'index. */
export function rafraichirIndexMd() {
  const index = lireEffets();
  fs.writeFileSync(FICHIERS.md, rendreIndexMd(index));
  return index;
}
