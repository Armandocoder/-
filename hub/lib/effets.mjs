/**
 * Construit l'index des effets. Ne lit que l'espace de travail et donnees/.
 * Retourne l'objet index (non écrit) plus un diagnostic.
 */
export function construireEffets() {
  const t0 = Date.now();
  const vocab = lireVocabulaire();
  const mapping = lireMapping();
  const registry = readJSONSafe(REGISTRY, 64 * 1024 * 1024);
  if (!registry || !Array.isArray(registry.styles)) throw new Error(`registry introuvable : ${REGISTRY} (lance node scripts/style-library/build-registry.mjs dans la v1)`);
  const analyse = readJSONSafe(ANALYSE, 16 * 1024 * 1024) || {};
  const epingles = lireEpingles();

  const effetsVocab = vocab.effets.map((e) => e.id);
  const effetInfo = new Map(vocab.effets.map((e) => [e.id, e]));
  const regTraitements = compilerRegles(mapping.traitements);
  const regSecondaires = compilerRegles(mapping.traitements_secondaires);
  const purposes = mapping.purposes || {};
  const cartesMap = mapping.cartes || {};
  const exclues = new Set(mapping.chaines_exclues || []);
  const avertissements = [];
  const purposesInconnus = new Map();

  function verifEffet(id, ou) {
    if (!id) return null;
    if (!effetInfo.has(id)) { avertissements.push(`effet « ${id} » hors vocabulaire (${ou})`); return null; }
    return id;
  }
  function charteDe(effet, override) {
    if (override === 'neutre' || override === 'habille') return override;
    const e = effetInfo.get(effet);
    return e && e.neutre ? 'neutre' : 'habille';
  }
  function secondairesDepuisTraitement(traitement, idCarte, primaire) {
    const tokens = uniq([...String(traitement || '').split(/[-_.]+/), ...String(idCarte || '').split('.').slice(2), String(traitement || '')]);
    const out = [];
    for (const tk of tokens) {
      if (!tk) continue;
      for (const r of regSecondaires) {
        if (r.re.test(tk) && r.effet !== primaire && effetInfo.has(r.effet)) out.push(r.effet);
      }
    }
    return uniq(out).slice(0, 3);
  }

  const chaines = [];
  const entrees = [];
  const parChaine = new Map();

  // --- 1. les styles de la style-library : une chaîne chacun, cartes jouables ---
  for (const st of registry.styles) {
    if (exclues.has(st.id)) continue;
    const meta = (mapping.chaines || {})[st.id] || {};
    const styleJson = readJSONSafe(path.join(ROOT, 'style-library', st.folder, 'style.json'), 8 * 1024 * 1024) || { cards: [] };
    const metaCartes = new Map((styleJson.cards || []).map((c) => [c.id, c]));
    const an = analyse[`style-${st.id}`] || null;
    const chaine = {
      id: st.id,
      nom: meta.nom || st.name,
      note: meta.note || '',
      ordre: meta.ordre != null ? meta.ordre : 50,
      source: 'style-library',
      dossier: `style-library/${st.folder}`,
      design: siExiste(`style-library/${st.folder}/DESIGN.md`),
      niveau: an ? an.niveau || null : (st.id === 'maison' ? 'charte' : null),
      pourquoi: an ? an.pourquoi || '' : '',
      resume: an ? an.resume || '' : (st.inspiration || '').slice(0, 240),
      ambiance: an ? an.ambiance || null : null,
      palette: st.palette || null,
      fonts: st.fonts || null,
      format_defaut: '16:9',
      n_cartes: 0, n_variantes: 0,
      // le style comme référence d'inspiration, lui, est en vitrine
      vitrine: `style-${st.id}`,
      epingle: !!(epingles.get(`style-${st.id}`) && epingles.get(`style-${st.id}`).epingle),
    };
    chaines.push(chaine);
    parChaine.set(st.id, chaine);

    const plis = new Map(); // `${purpose}` -> bucket des variantes générées
    let nVert = 0;
    for (const c of st.cards || []) {
      const mc = metaCartes.get(c.id) || {};
      const traitement = mc.treatment || c.id.split('.').slice(3).join('.') || '';
      const fichierRel = `style-library/${c.file}`;
      const prev = c.preview || {};
      const posterRel = prev.poster ? `style-library/${prev.poster}` : null;
      const mp4Rel = prev.mp4 ? `style-library/${prev.mp4}` : null;

      // l'effet : carte nommée > motif sur l'id/traitement > purpose
      const over = cartesMap[c.id] || {};
      let effet = verifEffet(over.effet, c.id);
      if (!effet) {
        const cle = `${c.id} ${traitement} ${c.file}`;
        const r = regTraitements.find((x) => x.re.test(cle));
        if (r) effet = verifEffet(r.effet, `traitement ${r.re.source}`);
      }
      if (!effet) {
        if (purposes[c.purpose]) effet = verifEffet(purposes[c.purpose], `purpose ${c.purpose}`);
        else purposesInconnus.set(c.purpose, (purposesInconnus.get(c.purpose) || 0) + 1);
      }
      if (!effet) effet = 'titre';

      if (mc.generated) {
        const k = `${c.tier}|${c.purpose}|${effet}`;
        if (!plis.has(k)) plis.set(k, { tier: c.tier, purpose: c.purpose, effet, cartes: [], slots: new Set(), premiere: null });
        const b = plis.get(k);
        b.cartes.push({ id: c.id, traitement, fichier: fichierRel });
        for (const s of c.slots || []) b.slots.add(s);
        if (!b.premiere) b.premiere = { fichier: fichierRel, poster: posterRel, mp4: mp4Rel };
        continue;
      }

      const ent = enteteCarte(fichierRel);
      const w = (ent && ent.w) || 1920, h = (ent && ent.h) || 1080;
      const format = mc.format || (h > w ? '9:16' : '16:9');
      if (format === '9:16') nVert++;
      const secondaires = uniq([...(over.secondaires || []).filter((x) => effetInfo.has(x)), ...secondairesDepuisTraitement(traitement, c.id, effet)]).filter((x) => x !== effet).slice(0, 3);
      entrees.push({
        id: c.id,
        nature: 'carte',
        chaine: st.id,
        effet,
        effets_secondaires: secondaires,
        titre: (ent && ent.titre) || humaniser(traitement || c.id.split('.').pop()),
        titre_traitement: humaniser(traitement || c.id.split('.').pop()),
        tier: c.tier,
        purpose: c.purpose,
        traitement,
        format,
        charte: charteDe(effet, over.charte),
        niveau: chaine.niveau === 'charte' ? null : chaine.niveau,
        fichier: existe(fichierRel) ? fichierRel : null,
        fichier_manquant: !existe(fichierRel),
        slots: (c.slots || []).map((s) => (typeof s === 'string' ? s : s.name)),
        duree: c.duration || null,
        dimensions: { w, h },
        apercu: {
          live: existe(fichierRel) ? fichierRel : null,
          poster: siExiste(posterRel),
          mp4: siExiste(mp4Rel),
          w, h,
        },
        mecanique: (ent && ent.commentaire) || mc.notes || '',
        notes: mc.notes || '',
        epingle: false,
        note_epingle: '',
      });
      chaine.n_cartes++;
    }
    // une entrée par pli de variantes
    for (const b of plis.values()) {
      const n = b.cartes.length;
      const canevas = {};
      const options = new Map();
      for (const v of b.cartes) {
        const m = /^(cream|olive|navy)/.exec(v.traitement);
        const k = m ? m[1] : 'autre';
        canevas[k] = (canevas[k] || 0) + 1;
        for (const tk of v.traitement.replace(/^(cream|olive|navy)-?/, '').split('-').filter(Boolean)) options.set(tk, (options.get(tk) || 0) + 1);
      }
      const optionsTxt = [...options.entries()].sort((x, y) => y[1] - x[1]).map(([k, n]) => `${k} (${n})`).join(', ');
      const ent = b.premiere ? enteteCarte(b.premiere.fichier) : null;
      const w = (ent && ent.w) || 1920, h = (ent && ent.h) || 1080;
      const idPli = `${st.id}.${b.tier === 'tier1' ? 't1' : b.tier === 'tier2' ? 't2' : b.tier}.${b.purpose}.variantes`;
      entrees.push({
        id: idPli,
        nature: 'carte',
        chaine: st.id,
        effet: b.effet,
        effets_secondaires: [],
        titre: `${n} variantes générées · ${b.purpose}`,
        tier: b.tier,
        purpose: b.purpose,
        traitement: 'variantes',
        format: h > w ? '9:16' : '16:9',
        charte: charteDe(b.effet),
        niveau: chaine.niveau === 'charte' ? null : chaine.niveau,
        fichier: b.premiere ? b.premiere.fichier : null,
        fichier_manquant: false,
        slots: [...b.slots],
        duree: null,
        dimensions: { w, h },
        apercu: { live: b.premiere ? siExiste(b.premiere.fichier) : null, poster: b.premiere ? siExiste(b.premiere.poster) : null, mp4: b.premiere ? siExiste(b.premiere.mp4) : null, w, h },
        mecanique: `${n} déclinaisons générées de la carte ${b.purpose} (${Object.entries(canevas).map(([k, v]) => `${v} ${k}`).join(', ')}). Le traitement nomme chaque déclinaison : le canevas d'abord, puis ses options. Options rencontrées ici : ${optionsTxt}. Choisir par le traitement, le fichier suit.`,
        notes: '',
        variantes: { n, canevas, cartes: b.cartes },
        epingle: false,
        note_epingle: '',
      });
      chaine.n_variantes += n;
    }
    if (chaine.n_cartes && nVert > chaine.n_cartes / 2) chaine.format_defaut = '9:16';

  }

  // --- 2. épingles, ma charte, tri, matrice ---
  appliquerEpingles(entrees, epingles);
  chaines.sort((a, b) => a.ordre - b.ordre || a.nom.localeCompare(b.nom, 'fr'));
  const ordreChaine = new Map(chaines.map((c, i) => [c.id, i]));
  const ordreEffet = new Map(effetsVocab.map((e, i) => [e, i]));
  const NIV = { pepite: 0, solide: 1, faible: 3 };
  entrees.sort((a, b) =>
    (ordreChaine.get(a.chaine) || 0) - (ordreChaine.get(b.chaine) || 0) ||
    (ordreEffet.get(a.effet) || 0) - (ordreEffet.get(b.effet) || 0) ||
    (a.traitement === 'variantes' ? 1 : 0) - (b.traitement === 'variantes' ? 1 : 0) ||
    ((NIV[a.niveau] != null ? NIV[a.niveau] : 2) - (NIV[b.niveau] != null ? NIV[b.niveau] : 2)) ||
    String(a.id).localeCompare(String(b.id)));

  const matrice = {};
  for (const c of chaines) { matrice[c.id] = {}; for (const e of effetsVocab) matrice[c.id][e] = 0; }
  const parEffet = {};
  for (const e of effetsVocab) parEffet[e] = 0;
  for (const x of entrees) {
    if (matrice[x.chaine]) matrice[x.chaine][x.effet] = (matrice[x.chaine][x.effet] || 0) + 1;
    parEffet[x.effet] = (parEffet[x.effet] || 0) + 1;
  }
  for (const [p, n] of purposesInconnus) avertissements.push(`purpose « ${p} » absent de mapping.purposes (${n} cartes, classées en titre)`);

  const index = {
    schema: 1,
    a_propos: 'La boîte à outils du montage : les cartes jouables de la style-library, classées par chaîne et par type d\'effet. dans_ma_charte distingue ce que le créateur monte (sa charte 10-maison, les chaînes et cartes adoptées dans donnees/ma-charte.json) de ce qui n\'est que de l\'inspiration. L\'inspiration à regarder (Pocinho, Prompt Motion, styles) est dans donnees/vitrine/index.json.',
    genere_le: new Date().toISOString(),
    genere_par: 'scripts/construire-effets.mjs',
    duree_ms: Date.now() - t0,
    vocabulaire: { valide: !!vocab.valide, valide_le: vocab.valide_le || null, propose_le: vocab.propose_le || null, familles: vocab.familles || [], effets: vocab.effets },
    sources: {
      registry: { cartes: registry.cardCount || null, styles: registry.styleCount || registry.styles.length, generees: entrees.reduce((n, x) => n + (x.variantes ? x.variantes.n : 0), 0) },
      inspiration: 'donnees/vitrine/index.json',
    },
    resume: {
      entrees: entrees.length,
      cartes: entrees.length,
      chaines: chaines.length,
      effets: effetsVocab.length,
      epinglees: entrees.filter((x) => x.epingle).length,
      par_effet: parEffet,
    },
    chaines,
    entrees,
    matrice,
    avertissements,
  };
  appliquerMaCharte(index);
  const diagnostic = { purposes_inconnus: [...purposesInconnus.entries()] };
  return { index, diagnostic };
}

// --- INDEX.md : la version lisible par le skill design-beats --------------------

function ligneEntree(x) {
  const bits = [];
  bits.push(x.nature === 'carte' ? `carte \`${x.id}\`` : `référence \`${x.id}\``);
  if (x.titre && x.nature === 'reference') bits.push(`**${x.titre}**`);
  bits.push(x.format);
  bits.push(x.charte === 'neutre' ? 'neutre' : 'habillé');
  
  if (x.tier && x.traitement !== 'variantes') bits.push(x.tier);
  if (x.effets_secondaires && x.effets_secondaires.length) bits.push(`aussi : ${x.effets_secondaires.join(', ')}`);
  if (x.slots && x.slots.length) bits.push(`slots ${x.slots.join(', ')}`);
  if (x.variantes) bits.push(`${x.variantes.n} variantes (${Object.entries(x.variantes.canevas).map(([k, v]) => `${v} ${k}`).join(', ')})`);
  if (x.fichier) bits.push(`\`${x.fichier}\``);
  if (x.apercu && x.apercu.mp4 && x.nature === 'reference') bits.push(`démo \`${x.apercu.mp4}\``);
  let s = `- ${bits.join(' · ')}`;
  const meca = x.nature === 'reference' ? [x.resume, x.mecanique].filter(Boolean).join(' ') : x.mecanique;
  if (meca) s += ` — ${meca.replace(/\s+/g, ' ').slice(0, 180)}${meca.length > 180 ? '…' : ''}`;
  if (x.epingle && x.note_epingle) s += `\n  > ${x.note_epingle.replace(/\n/g, ' ')}`;
  return s;
}

